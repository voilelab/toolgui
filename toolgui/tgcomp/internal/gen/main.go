// Command gen writes tgcomp's forwarding files from the tc* packages.
//
// A declaration marked with a //tgcomp:export directive is forwarded: a func
// by a wrapper calling it, a type by an alias, and a const group by a group
// of the same names. Run it with go generate in toolgui/tgcomp.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

const (
	directive  = "//tgcomp:export"
	modulePath = "github.com/voilelab/toolgui/toolgui/tgcomp/"
	header     = "// Code generated by tgcomp/internal/gen; DO NOT EDIT.\n\n"
)

// qualifierRe matches a tc* package qualifier in a doc comment, with the
// opening bracket of a doc link.
var qualifierRe = regexp.MustCompile(`\[?\btc[a-z]+\.[A-Z][A-Za-z0-9_]*`)

func main() {
	files, err := generate(".")
	if err != nil {
		log.Fatal(err)
	}

	for name, src := range files {
		if err := os.WriteFile(name, src, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

// outName is the generated file of package pkg, e.g. tcchat -> chat_gen.go.
func outName(pkg string) string {
	return strings.TrimPrefix(pkg, "tc") + "_gen.go"
}

// generate returns each generated file's name, relative to root, and source.
// root is the tgcomp directory.
func generate(root string) (map[string][]byte, error) {
	dirs, err := filepath.Glob(filepath.Join(root, "tc*"))
	if err != nil {
		return nil, err
	}
	sort.Strings(dirs)

	// Every package's exports first: a doc comment may name another's.
	all := map[string]map[string]bool{}
	for _, dir := range dirs {
		if fi, err := os.Stat(dir); err != nil || !fi.IsDir() {
			continue
		}

		names, err := markedNames(dir)
		if err != nil {
			return nil, err
		}

		if len(names) > 0 {
			all[filepath.Base(dir)] = names
		}
	}

	out := map[string][]byte{}
	for pkg := range all {
		src, err := generatePackage(filepath.Join(root, pkg), pkg, all)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", pkg, err)
		}

		out[filepath.Join(root, outName(pkg))] = src
	}

	return out, nil
}

// markedNames returns the names a package's markers export.
func markedNames(dir string) (map[string]bool, error) {
	g := &pkgGen{fset: token.NewFileSet()}

	files, err := g.parse(dir)
	if err != nil {
		return nil, err
	}

	names := map[string]bool{}
	for _, f := range files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if marked(d.Doc) && d.Recv == nil {
					names[d.Name.Name] = true
				}

			case *ast.GenDecl:
				if !marked(d.Doc) {
					continue
				}

				for _, sp := range d.Specs {
					switch sp := sp.(type) {
					case *ast.TypeSpec:
						names[sp.Name.Name] = true
					case *ast.ValueSpec:
						for _, n := range sp.Names {
							names[n.Name] = true
						}
					}
				}
			}
		}
	}

	return names, nil
}

// pkgGen holds what generating one package needs.
type pkgGen struct {
	pkg  string
	fset *token.FileSet

	// all are the names each package exports, to rewrite doc references.
	all map[string]map[string]bool

	// types are the package's top-level type names; exported says which are
	// forwarded, so tgcomp has an alias of the same name.
	types    map[string]bool
	exported map[string]bool

	// imports are the import paths the output uses, by name.
	imports map[string]string

	body bytes.Buffer
}

func generatePackage(dir, pkg string, all map[string]map[string]bool) ([]byte, error) {
	g := &pkgGen{
		pkg:      pkg,
		fset:     token.NewFileSet(),
		all:      all,
		types:    map[string]bool{},
		exported: map[string]bool{},
		imports:  map[string]string{pkg: modulePath + pkg},
	}

	files, err := g.parse(dir)
	if err != nil {
		return nil, err
	}

	// Collect types first: a signature may name a type declared later.
	for _, f := range files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}

			for _, sp := range gd.Specs {
				name := sp.(*ast.TypeSpec).Name.Name
				g.types[name] = true
				if marked(gd.Doc) {
					g.exported[name] = true
				}
			}
		}
	}

	for _, f := range files {
		for _, d := range f.Decls {
			if err := g.decl(f, d); err != nil {
				return nil, fmt.Errorf("%s: %w", g.fset.Position(d.Pos()), err)
			}
		}
	}

	var src bytes.Buffer
	src.WriteString(header + "package tgcomp\n\nimport (\n")

	names := make([]string, 0, len(g.imports))
	for name := range g.imports {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		path := g.imports[name]
		if filepath.Base(path) == name {
			fmt.Fprintf(&src, "\t%q\n", path)
		} else {
			fmt.Fprintf(&src, "\t%s %q\n", name, path)
		}
	}

	src.WriteString(")\n")
	src.Write(g.body.Bytes())

	return format.Source(src.Bytes())
}

// parse returns the package's non-test files in file name order.
func (g *pkgGen) parse(dir string) ([]*ast.File, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}

	var files []*ast.File
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}

		f, err := parser.ParseFile(g.fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}

		files = append(files, f)
	}

	return files, nil
}

// marked reports whether a doc comment carries the directive.
func marked(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}

	return slices.ContainsFunc(doc.List, func(c *ast.Comment) bool {
		return c.Text == directive
	})
}

func (g *pkgGen) decl(f *ast.File, d ast.Decl) error {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if !marked(d.Doc) {
			return nil
		}
		if d.Recv != nil {
			return fmt.Errorf("%s: methods can't be exported", d.Name.Name)
		}
		return g.funcDecl(f, d)

	case *ast.GenDecl:
		if !marked(d.Doc) {
			return nil
		}

		switch d.Tok {
		case token.TYPE:
			return g.typeDecl(f, d)
		case token.CONST:
			return g.constDecl(d)
		default:
			return fmt.Errorf("only funcs, types and consts can be exported")
		}
	}

	return nil
}

func (g *pkgGen) funcDecl(f *ast.File, d *ast.FuncDecl) error {
	typ := d.Type
	tparams := fieldNames(typ.TypeParams)

	if err := g.qualify(f, typ, tparams); err != nil {
		return err
	}

	// Name unnamed and blank params so the call can pass them on, avoiding
	// the names already taken.
	used := map[string]bool{}
	for _, name := range append(fieldNames(typ.Params), tparams...) {
		used[name] = true
	}

	next := 0
	synth := func() *ast.Ident {
		for used["p"+strconv.Itoa(next)] {
			next++
		}
		used["p"+strconv.Itoa(next)] = true
		return ast.NewIdent("p" + strconv.Itoa(next))
	}

	var args []string
	if typ.Params != nil {
		for _, field := range typ.Params.List {
			if len(field.Names) == 0 {
				field.Names = []*ast.Ident{synth()}
			}

			for i, n := range field.Names {
				if n.Name == "_" {
					n = synth()
					field.Names[i] = n
				}

				arg := n.Name
				if _, ok := field.Type.(*ast.Ellipsis); ok {
					arg += "..."
				}
				args = append(args, arg)
			}
		}
	}

	call := g.pkg + "." + d.Name.Name + typeArgs(tparams) + "(" + strings.Join(args, ", ") + ")"
	if typ.Results != nil && len(typ.Results.List) > 0 {
		call = "return " + call
	}

	sig := &ast.FuncDecl{Name: d.Name, Type: typ}

	g.doc(d.Doc)
	g.body.WriteString(g.print(sig))
	fmt.Fprintf(&g.body, " {\n\t%s\n}\n", call)

	return nil
}

func (g *pkgGen) typeDecl(f *ast.File, d *ast.GenDecl) error {
	if d.Lparen.IsValid() {
		return fmt.Errorf("type groups can't be exported")
	}

	sp := d.Specs[0].(*ast.TypeSpec)
	tparams := fieldNames(sp.TypeParams)

	if sp.TypeParams != nil {
		if err := g.qualify(f, sp.TypeParams, tparams); err != nil {
			return err
		}
	}

	g.doc(d.Doc)
	g.body.WriteString("type " + sp.Name.Name)
	if sp.TypeParams != nil {
		var fields []string
		for _, field := range sp.TypeParams.List {
			fields = append(fields, strings.Join(fieldNames(&ast.FieldList{List: []*ast.Field{field}}), ", ")+" "+g.print(field.Type))
		}
		g.body.WriteString("[" + strings.Join(fields, ", ") + "]")
	}
	fmt.Fprintf(&g.body, " = %s.%s%s\n", g.pkg, sp.Name.Name, typeArgs(tparams))

	return nil
}

func (g *pkgGen) constDecl(d *ast.GenDecl) error {
	g.doc(d.Doc)

	if names := d.Specs[0].(*ast.ValueSpec).Names; !d.Lparen.IsValid() && len(names) == 1 {
		fmt.Fprintf(&g.body, "const %s = %s.%s\n", names[0].Name, g.pkg, names[0].Name)
		return nil
	}

	g.body.WriteString("const (\n")

	first := true
	for _, sp := range d.Specs {
		vs := sp.(*ast.ValueSpec)

		var names []string
		for _, n := range vs.Names {
			if n.IsExported() {
				names = append(names, n.Name)
			}
		}

		if len(names) == 0 {
			continue
		}

		if !first && vs.Doc != nil {
			g.body.WriteString("\n")
		}
		first = false
		g.comment(vs.Doc)

		for _, name := range names {
			fmt.Fprintf(&g.body, "\t%s = %s.%s\n", name, g.pkg, name)
		}
	}

	g.body.WriteString(")\n")

	return nil
}

// doc writes a blank line and a doc comment, without the directive and the
// blank comment line before it.
func (g *pkgGen) doc(doc *ast.CommentGroup) {
	g.body.WriteString("\n")
	g.comment(doc)
}

// comment writes doc's lines, without the directive and the blank comment
// line before it.
func (g *pkgGen) comment(doc *ast.CommentGroup) {
	if doc == nil {
		return
	}

	var lines []string
	for _, c := range doc.List {
		if c.Text != directive {
			lines = append(lines, c.Text)
		}
	}

	for len(lines) > 0 && lines[len(lines)-1] == "//" {
		lines = lines[:len(lines)-1]
	}

	for _, l := range lines {
		g.body.WriteString(g.requalify(l) + "\n")
	}
}

// requalify points a doc line's references to forwarded tc* names at tgcomp:
// tcX.Name becomes tgcomp.Name, and the doc link [tcX.Name] becomes [Name].
func (g *pkgGen) requalify(line string) string {
	return qualifierRe.ReplaceAllStringFunc(line, func(m string) string {
		link := strings.HasPrefix(m, "[")
		pkg, name, _ := strings.Cut(strings.TrimPrefix(m, "["), ".")

		if !g.all[pkg][name] {
			return m
		}
		if link {
			return "[" + name
		}
		return "tgcomp." + name
	})
}

// qualify rewrites the type expressions under n for use from tgcomp: a type
// of the package keeps its name if tgcomp aliases it, and is qualified
// otherwise; an imported package is recorded for the import block.
func (g *pkgGen) qualify(f *ast.File, n ast.Node, tparams []string) error {
	var err error

	ast.Inspect(n, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.Field:
			// Visit only the type: names are params.
			if e := g.qualify(f, n.Type, tparams); e != nil && err == nil {
				err = e
			}
			return false

		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok {
				path, e := importPath(f, id.Name)
				if e != nil && err == nil {
					err = e
				}
				g.imports[id.Name] = path
			}
			return false

		case *ast.Ident:
			if !g.types[n.Name] || slices.Contains(tparams, n.Name) || g.exported[n.Name] {
				return false
			}

			if !n.IsExported() && err == nil {
				err = fmt.Errorf("unexported type %s in an exported signature", n.Name)
			}
			n.Name = g.pkg + "." + n.Name
		}

		return true
	})

	return err
}

// importPath returns the path f imports under name.
func importPath(f *ast.File, name string) (string, error) {
	for _, imp := range f.Imports {
		path, _ := strconv.Unquote(imp.Path.Value)
		if (imp.Name != nil && imp.Name.Name == name) ||
			(imp.Name == nil && filepath.Base(path) == name) {
			return path, nil
		}
	}

	return "", fmt.Errorf("no import named %s", name)
}

func fieldNames(fl *ast.FieldList) []string {
	if fl == nil {
		return nil
	}

	var names []string
	for _, field := range fl.List {
		for _, n := range field.Names {
			names = append(names, n.Name)
		}
	}

	return names
}

func typeArgs(tparams []string) string {
	if len(tparams) == 0 {
		return ""
	}

	return "[" + strings.Join(tparams, ", ") + "]"
}

func (g *pkgGen) print(n any) string {
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, token.NewFileSet(), n); err != nil {
		panic(err)
	}

	return buf.String()
}
